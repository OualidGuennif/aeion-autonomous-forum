-- Feature 001 (app skeleton and settings), 002 (PostgreSQL cutover), 003 (test harness).
-- Flyway is the single versioned authority: it applies this file once, in a transaction, and
-- records it in flyway_schema_history. The application role later receives DML-only grants from
-- the operator, so it can never repeat or alter this schema.

CREATE TABLE settings (
    name       TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_ns BIGINT NOT NULL
);

CREATE TABLE accounts (
    id         TEXT PRIMARY KEY,
    username   TEXT NOT NULL UNIQUE,
    password   TEXT NOT NULL,
    role       TEXT NOT NULL DEFAULT 'member',
    created_ns BIGINT NOT NULL,
    locked_ns  BIGINT,
    failures   INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE sessions (
    id         TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id),
    issued_ns  BIGINT NOT NULL,
    expires_ns BIGINT NOT NULL,
    revoked_ns BIGINT
);

CREATE TABLE threads (
    id         TEXT PRIMARY KEY,
    title      TEXT NOT NULL,
    body       TEXT NOT NULL,
    author_id  TEXT NOT NULL REFERENCES accounts(id),
    created_ns BIGINT NOT NULL
);

CREATE INDEX idx_threads_created ON threads(created_ns DESC);
CREATE INDEX idx_sessions_account ON sessions(account_id);

-- The audit chain: every row digests its predecessor, so a removed or edited event breaks the
-- chain and the operator's validate refuses. The application role holds no write grant here.
CREATE TABLE schema_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at_ns       BIGINT NOT NULL,
    migration   TEXT NOT NULL,
    detail      TEXT,
    prev_digest TEXT NOT NULL,
    row_digest  TEXT NOT NULL
);
